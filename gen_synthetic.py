"""Generates synthetic QIF traffic for two common .NET HTTP/3 workloads (deterministic, seeded).

grpc-*.qif : 500 unary gRPC calls from a grpc-dotnet client to a Kestrel server, plus trailers.
rest-*.qif : 500 JSON API calls from HttpClient to a Kestrel server.

Per-connection constants (bearer token, user-agent) repeat on every request; per-request values
(traceparent, ids, content-length, date) change. That mix is exactly what a dynamic table can or
cannot exploit, so the numbers depend on it - see README for the assumptions.
"""

import base64
import os
import random
from datetime import datetime, timedelta, timezone

REQUESTS = 500
OUT = os.path.join(os.path.dirname(__file__), "corpus")
rng = random.Random(38961)


def b64url(n_bytes):
    return base64.urlsafe_b64encode(rng.randbytes(n_bytes)).rstrip(b"=").decode()


def hexid(n_bytes):
    return rng.randbytes(n_bytes).hex()


# A typical Entra ID / OAuth access token is 1-2 KB; this one is ~1.1 KB.
JWT = f"{b64url(48)}.{b64url(600)}.{b64url(256)}"
TRACE_FLAGS = "01"
START = datetime(2026, 10, 16, 9, 0, 0, tzinfo=timezone.utc)


def http_date(i, per_second):
    return (START + timedelta(seconds=i // per_second)).strftime("%a, %d %b %Y %H:%M:%S GMT")


def traceparent():
    return f"00-{hexid(16)}-{hexid(8)}-{TRACE_FLAGS}"


def grpc():
    methods = ["/orders.v1.OrderService/GetOrder", "/orders.v1.OrderService/ListOrders",
               "/catalog.v1.Catalog/GetProduct", "/catalog.v1.Catalog/Search", "/auth.v1.Session/Refresh"]
    req, resp = [], []
    for i in range(REQUESTS):
        req.append([
            (":method", "POST"), (":scheme", "https"), (":authority", "api.contoso.com"),
            (":path", rng.choice(methods)),
            ("content-type", "application/grpc"), ("te", "trailers"),
            ("user-agent", "grpc-dotnet/2.67.0 (.NET 10.0.0; CLR 10.0.0; net10.0; linux; x64)"),
            ("grpc-accept-encoding", "identity,gzip,deflate"),
            ("grpc-timeout", "30S"),
            ("authorization", f"Bearer {JWT}"),
            ("traceparent", traceparent()),
        ])
        resp.append([
            (":status", "200"), ("content-type", "application/grpc"),
            ("date", http_date(i, per_second=20)), ("server", "Kestrel"),
            ("grpc-accept-encoding", "identity,gzip,deflate"),
        ])
        resp.append([("grpc-status", "0")])  # trailers
    return req, resp


def rest():
    req, resp = [], []
    for i in range(REQUESTS):
        post = rng.random() < 0.3
        order = rng.randint(100000, 999999)
        headers = [
            (":method", "POST" if post else "GET"), (":scheme", "https"), (":authority", "api.contoso.com"),
            (":path", "/v1/orders" if post else f"/v1/orders/{order}?include=lines,customer"),
            ("accept", "application/json"),
            ("authorization", f"Bearer {JWT}"),
            ("traceparent", traceparent()),
            ("user-agent", "Contoso.Shop/4.2.1"),
        ]
        if post:
            headers += [("content-type", "application/json; charset=utf-8"),
                        ("content-length", str(rng.randint(180, 2400)))]
        req.append(headers)
        resp.append([
            (":status", "201" if post else "200"),
            ("content-type", "application/json; charset=utf-8"),
            ("date", http_date(i, per_second=20)), ("server", "Kestrel"),
            ("content-length", str(rng.randint(300, 9000))),
            ("cache-control", "no-store"),
            ("request-context", "appId=cid-v1:5c1d1f3e-8d55-4b5a-9a3c-4f3b2a8f1e77"),
        ])
    return req, resp


def write_qif(name, blocks):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(f"# synthetic, generated by gen_synthetic.py ({len(blocks)} header lists)\n")
        for block in blocks:
            for k, v in block:
                f.write(f"{k}\t{v}\n")
            f.write("\n")


if __name__ == "__main__":
    for prefix, (requests, responses) in {"grpc": grpc(), "rest": rest()}.items():
        write_qif(f"{prefix}-req.qif", requests)
        write_qif(f"{prefix}-resp.qif", responses)
    print("wrote corpus/{grpc,rest}-{req,resp}.qif")
